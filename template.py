#!/usr/bin/env python3
"""Keep projects made from this template current.

  ./template.py status [--root DIR]...
      Every project under ~/workspace (or each --root): the template commit it is stamped with and
      how many template commits it is behind, or that it has no stamp yet, and any option whose
      files it holds though its stamp has the option off.

  ./template.py update PROJECT [--to REVISION]
      Merge the template's changes since the project's stamp into PROJECT. The template is rendered
      at the stamped commit and at REVISION (default HEAD) with the project's name and options, and
      every file that changed between the two is merged three ways into the project with
      `git merge-file`. Conflicts are left marked in the files; the files scripts/modules.py
      generates are regenerated instead of merged. Nothing is committed. PROJECT must be a git
      checkout with no uncommitted changes, so `git diff` shows exactly what the update did. When
      PROJECT holds a file only an option renders (Fuzz/, say) and its stamp has that option off,
      a note names the option and the `stamp` or `add` command that records it (for an option newer
      than the stamped commit, an `update --to` its first commit, then `add`); the update goes on.
      A library or server stamped before --performance existed gets a note that the template now
      renders the throwing error convention, and how to keep trap and `checked:` spellings.

  ./template.py stamp PROJECT [--type library|server|embedded|mcp|app] [--benchmarks] [--mutation] [--fuzz]
                              [--differential] [--wasm] [--explore] [--views] [--examples] [--ios] [--simulator] [--performance]
                              [--fly] [--database] [--no-ci]
                              [--trunk] [--name NAME] [--commit REVISION]
      Record that PROJECT matches the template at REVISION (default HEAD) with these options, for a
      project made before bootstrap.sh wrote stamps. Later updates merge only what changed after it.

  ./template.py add PROJECT [--benchmarks] [--mutation] [--fuzz] [--differential] [--wasm] [--explore]
                            [--views] [--examples] [--ios] [--simulator] [--performance] [--fly] [--database] [--ci] [--trunk]
      Turn options on in a project made without them. The template is rendered at the stamped commit
      with the stamp's options and again with the new ones added, and every file that differs is
      merged three ways into the project, as `update` does; the stamp then records the options. It
      refuses an option the stamped commit's bootstrap.sh doesn't know (run `update` first) or one
      that doesn't apply to the project's type. Nothing is committed; PROJECT must have no
      uncommitted changes.

  ./template.py remove PROJECT [--benchmarks] [--mutation] [--fuzz] [--differential] [--wasm] [--explore]
                               [--views] [--examples] [--ios] [--simulator] [--performance] [--fly] [--database] [--ci]
                               [--trunk]
      Turn options off, the mirror of `add`. The template is rendered at the stamped commit with the
      stamp's options and again with these turned off, and every file that differs is merged three
      ways into the project, as `add` does: what the options brought is removed where the project
      left it alone, kept and reported where it changed it, and files the project added itself stay.
      The stamp then records the options off. It refuses an option the stamp doesn't have on, and
      --ci while --trunk stays on (the merge queue waits for CI's checks), and --simulator while
      --ios stays on (--ios brings the same files). Removing --ios takes the test host with the app
      unless the stamp has --simulator too: add --simulator first to keep simulator tests. Nothing
      is committed; PROJECT must have no uncommitted changes.

  ./template.py retype PROJECT --type library|server|embedded|mcp|app
      Change a project's type, such as a library that grew into an MCP server. The template is
      rendered at the stamped commit as the stamp's type and again as the new one, and every file
      that differs is merged three ways into the project, as `add` does; the stamp then records the
      type. It refuses a type the stamped commit doesn't know (run `update` first) and options the
      new type doesn't take. Nothing is committed; PROJECT must have no uncommitted changes.

The stamp is PROJECT/.template.json, written by bootstrap.sh. .github/docs/updating.md describes
the workflow.
"""
import argparse
import collections
import importlib.util
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

TEMPLATE = pathlib.Path(__file__).resolve().parent
STAMP = ".template.json"
GENERATED = "GENERATED by scripts/modules.py"


def git(*args, cwd=TEMPLATE, check=True):
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed in {cwd}:\n{result.stderr.strip()}")
    return result.stdout.strip()


def resolve(revision):
    return git("rev-parse", "--verify", f"{revision}^{{commit}}")


def read_stamp(project):
    path = project / STAMP
    if not path.is_file():
        sys.exit(f"{project} has no {STAMP}; adopt it first with ./template.py stamp (.github/docs/updating.md)")
    return json.loads(path.read_text())


def write_stamp(project, stamp):
    (project / STAMP).write_text(json.dumps(stamp, indent=2) + "\n")


FEATURES = ("benchmarks", "mutation", "fuzz", "differential", "wasm", "explore", "views", "examples", "ios", "simulator", "performance", "fly", "database", "ci", "trunk")
# Options on unless the stamp says otherwise: a stamp from before the option had it.
ON_BY_DEFAULT = ("ci",)


def enabled(stamp, feature):
    return stamp.get(feature, feature in ON_BY_DEFAULT)


# Options another brings with it: --ios brings what --simulator does (the test host, the simulator
# settings, tools/ios.bzl), so a project with --ios has --simulator's files without its flag.
IMPLIED_BY = {"simulator": "ios"}


def has(stamp, feature):
    """Whether the project has the option's files, on its own flag or through one that implies it."""
    return enabled(stamp, feature) or (feature in IMPLIED_BY and enabled(stamp, IMPLIED_BY[feature]))


def options(stamp):
    """bootstrap.sh's flags for the stamp. Only the features that differ from bootstrap's defaults
    are passed, so a template commit older than an option, which doesn't know its flag, renders
    every stamp that keeps the default."""
    flags = ["--type", stamp["type"]]
    for feature in FEATURES:
        if enabled(stamp, feature) and feature not in ON_BY_DEFAULT:
            flags.append(f"--{feature}")
        elif not enabled(stamp, feature) and feature in ON_BY_DEFAULT:
            flags.append(f"--no-{feature}")
    return flags


# A file only the option renders, for each option whose files can be told apart: a manifest or
# script by the template's name rather than a directory a project might make for itself. A stamp
# written before an option existed has it off, so updates render without it and never reach the
# copy of its files a project made by hand; `unstamped_options` finds those.
SIGNATURES = {
    "benchmarks": "Benchmarks/Package.swift",
    "mutation": "scripts/mutate.py",
    "fuzz": "Fuzz/Package.swift",
    "differential": "Differential/Package.swift",
    "wasm": "scripts/wasi_test.py",
    "explore": "Explore/build.sh",
    # The app type renders the same lint, but views applies only to libraries.
    "views": "tools/lint.bzl",
    "examples": "Examples/Package.swift",
    "ios": "Apps/{name}/BUILD.bazel",
    "simulator": "tools/test_host/BUILD.bazel",
    "fly": "fly.toml",
    "database": "Sources/App/Database",
    "ci": ".github/workflows/CI.yml",
    "trunk": ".trunk/trunk.yaml",
}


def present(root, relative):
    """Whether `relative` exists under `root`, spelled as given: macOS's file system ignores case, so
    a project's own .github/workflows/ci.yml would otherwise pass for the template's CI.yml."""
    directory = root
    for part in pathlib.PurePosixPath(relative).parts:
        if not directory.is_dir() or part not in os.listdir(directory):
            return False
        directory = directory / part
    return True


def unstamped_options(project, stamp):
    """The options the stamp has off though the project holds a file only that option renders."""
    return [feature for feature, signature in SIGNATURES.items()
            if not has(stamp, feature)
            and (feature not in TYPE_ONLY or stamp["type"] in TYPE_ONLY[feature])
            and present(project, signature.format(name=stamp["name"]))]


def first_commit_with(feature, since):
    """The first template commit after `since` whose bootstrap.sh takes --<feature>, or None."""
    found = git("log", "--reverse", "--ancestry-path", "--format=%H", f"-S--{feature})", f"{since}..HEAD",
                "--", "bootstrap.sh", check=False).split()
    return found[0] if found else None


def unstamped_note(project, stamp):
    """A note naming the options `unstamped_options` finds and the commands that fix the stamp, or None.
    An option the stamped commit's bootstrap.sh doesn't take can't be stamped there (every later render
    would refuse the flag) or added there, so for it the note says to update past its first commit,
    then add it."""
    found = unstamped_options(project, stamp)
    if not found:
        return None
    script = git("show", f"{stamp['commit']}:bootstrap.sh", check=False)
    known = [feature for feature in found if not script or f"--{feature})" in script]
    unknown = [feature for feature in found if feature not in known]
    flags = " ".join(f"--{feature}" for feature in found)
    them = "it" if len(found) == 1 else "them"
    note = (f"Note: {project.name} has the files of {flags}, but its stamp has {them} off, so updates render "
            f"without {them} and never reach those files.")
    if known:
        known_flags = " ".join(f"--{feature}" for feature in known)
        corrected = dict(stamp, **{feature: True for feature in known})
        command = ["./template.py", "stamp", str(project), *options(corrected), "--name", stamp["name"],
                   "--commit", stamp["commit"][:12]]
        note += (f" If the files of {known_flags} match the template at the stamped commit, record "
                 f"{'it' if len(known) == 1 else 'them'}: `{' '.join(command)}`. Otherwise "
                 f"`./template.py add {project} {known_flags}` and resolve what differs.")
    if unknown:
        unknown_flags = " ".join(f"--{feature}" for feature in unknown)
        firsts = [first_commit_with(feature, stamp['commit']) for feature in unknown]
        # The latest of their first commits, so the update reaches every one of them.
        target = max(filter(None, firsts), key=lambda commit: int(git("rev-list", "--count", commit)), default=None)
        to = f" --to {target[:12]}" if target else ""
        note += (f" The stamped commit, {stamp['commit'][:12]}, has no {unknown_flags}"
                 f"{f' (from {target[:12]})' if target else ''}, so it can't be stamped or added there: "
                 f"`./template.py update {project}{to}` (or later), then `./template.py add {project} {unknown_flags}` "
                 f"and resolve what differs.")
    return note


def performance_note(project, stamp):
    """A note for a library or server stamped before --performance existed, or None. Its updates
    render without the option, which from then on means the throwing error convention."""
    if "performance" in stamp or stamp["type"] not in TYPE_ONLY["performance"]:
        return None
    return (f"Note: {project.name}'s stamp predates --performance. The template now renders the throwing "
            f"error convention by default: plain spellings throw a typed error, with no `checked:` spellings "
            f"and no traps that can fire at run time, so this update brings that to AGENTS.md's Errors section "
            f"and the Greetings example. A high-performance library keeps trap and `checked:` spellings with "
            f"`./template.py add {project} --performance` once the update is committed (or "
            f"`./template.py stamp` with --performance, if it already matches that render).")


def bootstrap_source(commit, scratch):
    """bootstrap.sh at `commit`, from an archive of the template extracted once into `scratch`."""
    source = scratch / f"template-{commit[:12]}"
    if not source.is_dir():
        source.mkdir()
        archive = subprocess.run(["git", "archive", commit], cwd=TEMPLATE, capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", str(source)], input=archive, check=True)
    return (source / "bootstrap.sh").read_text()


def render(commit, stamp, scratch, variant=""):
    """The template at `commit`, rendered with the stamp's name and options; returns its directory."""
    if "--render-only" not in bootstrap_source(commit, scratch):
        sys.exit(f"The template at {commit[:12]} predates --render-only; stamp the project at a later commit")
    bootstrap = scratch / f"template-{commit[:12]}" / "bootstrap.sh"
    rendered = scratch / f"rendered-{commit[:12]}{variant}"
    result = subprocess.run(["bash", str(bootstrap), "--render-only", *options(stamp), stamp["name"], str(rendered)],
                            capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"Rendering the template at {commit[:12]} failed:\n{result.stderr.strip()}")
    return rendered


def declared_swift(project):
    """The (SWIFT, SWIFT_TOOLCHAIN) that `project`'s scripts/modules.py declares, or None for one from
    before the template declared them."""
    path = project / "scripts" / "modules.py"
    if not path.is_file():
        return None
    values = dict(re.findall(r'^(SWIFT|SWIFT_TOOLCHAIN) = "([^"]*)"$', path.read_text(), re.MULTILINE))
    if "SWIFT" not in values or "SWIFT_TOOLCHAIN" not in values:
        return None
    return values["SWIFT"], values["SWIFT_TOOLCHAIN"]


def rendered_swift(rendered, modules):
    """The Swift versions a render's files name: its record, else (a template from before it kept one)
    its manifest's tools version and the toolchain AGENTS.md has swiftly install."""
    recorded = modules.recorded_swift(rendered)
    if recorded:
        return recorded
    manifest = rendered / "Package.swift"
    floor = re.match(r"// swift-tools-version: (\S+)", manifest.read_text()) if manifest.is_file() else None
    agents = rendered / "AGENTS.md"
    toolchain = re.search(r"swiftly install (\d+\.\d+\.\d+)", agents.read_text()) if agents.is_file() else None
    return floor and floor.group(1), toolchain and toolchain.group(1)


def version_key(version):
    return tuple(int(part) for part in version.split("."))


def follow_project_swift(project, base, new):
    """Gives both renders the project's Swift versions when it chose its own, so every line naming
    them merges as the project's rather than conflicting; returns a note for the report, or None.
    The template's replacement is used for renders of any commit, which may predate it."""
    declared = declared_swift(project)
    if declared is None:
        return None
    spec = importlib.util.spec_from_file_location("template_modules", TEMPLATE / "scripts" / "modules.py")
    modules = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modules)
    if rendered_swift(base, modules) == declared:
        return None
    newer = rendered_swift(new, modules)
    for rendered in (base, new):
        modules.replace_swift(str(rendered), rendered_swift(rendered, modules), declared)
        declaration = rendered / "scripts" / "modules.py"
        if declaration.is_file():
            text = re.sub(r'^SWIFT = "[^"]*"$', f'SWIFT = "{declared[0]}"', declaration.read_text(), flags=re.MULTILINE)
            text = re.sub(r'^SWIFT_TOOLCHAIN = "[^"]*"$', f'SWIFT_TOOLCHAIN = "{declared[1]}"', text, flags=re.MULTILINE)
            declaration.write_text(text)
    if newer[0] and version_key(newer[0]) > version_key(declared[0]):
        return (f"The template now builds with Swift {newer[0]} ({newer[1]}); this project stays on {declared[0]} "
                f"({declared[1]}). To follow it, set SWIFT and SWIFT_TOOLCHAIN in scripts/modules.py and run `just modules`.")
    return None


def files(root):
    return {path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file() and not path.is_symlink()}


def is_generated(path):
    try:
        with open(path, encoding="utf-8") as file:
            # Package.swift has it on its fourth line, after the tools version and the import.
            return any(GENERATED in file.readline() for _ in range(5))
    except (UnicodeDecodeError, OSError):
        return False


def is_text(path):
    try:
        path.read_text(encoding="utf-8")
        return True
    except UnicodeDecodeError:
        return False


def install(source, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def delete(project, path):
    """Deletes `path` and the directories it leaves empty, up to `project`."""
    path.unlink()
    folder = path.parent
    while folder != project and not any(folder.iterdir()):
        folder.rmdir()
        folder = folder.parent


def merge(project, base, new, base_label, new_label):
    """Merges every file that changed from `base` to `new` into `project`; returns a report by outcome."""
    report = {name: [] for name in ("updated", "added", "removed", "merged", "conflicted", "duplicated",
                                    "kept", "skipped", "regenerated")}
    empty = base.parent / "empty"
    empty.write_text("")
    base_files = files(base)
    for relative in sorted(base_files | files(new)):
        if relative == STAMP:
            continue
        old, current, theirs = base / relative, project / relative, new / relative
        if old.is_file() and theirs.is_file() and old.read_bytes() == theirs.read_bytes():
            continue
        if is_generated(theirs if theirs.is_file() else old):
            if not theirs.is_file() and current.is_file() and is_generated(current):
                # Gone from the template: scripts/modules.py writes it again if the project still
                # lists what it was generated for.
                delete(project, current)
                report["removed"].append(relative)
            else:
                report["regenerated"].append(relative)
            continue
        if not theirs.is_file():
            if not current.is_file():
                continue
            if current.read_bytes() == old.read_bytes():
                delete(project, current)
                report["removed"].append(relative)
            else:
                report["kept"].append(f"{relative} (the template removed it; this project changed it)")
            continue
        if not current.is_file():
            if old.is_file():
                report["skipped"].append(f"{relative} (the template changed it; this project removed it)")
            elif removed := removed_directory(project, base_files, relative):
                report["skipped"].append(f"{relative} (the template added it to {removed}, which this project removed)")
            else:
                install(theirs, current)
                report["added"].append(relative)
            continue
        if current.read_bytes() == theirs.read_bytes():
            continue
        if old.is_file() and current.read_bytes() == old.read_bytes():
            install(theirs, current)
            report["updated"].append(relative)
            continue
        if not (is_text(current) and is_text(theirs) and (not old.is_file() or is_text(old))):
            report["conflicted"].append(f"{relative} (binary; the template's version is at {theirs})")
            continue
        before = current.read_text()
        result = subprocess.run(
            ["git", "merge-file", "-L", "project", "-L", base_label, "-L", new_label, str(current), str(old if old.is_file() else empty), str(theirs)],
            capture_output=True, text=True)
        if result.returncode < 0 or result.returncode > 127:
            sys.exit(f"git merge-file failed on {relative}:\n{result.stderr.strip()}")
        report["conflicted" if result.returncode > 0 else "merged"].append(relative)
        if result.returncode == 0:
            report["duplicated"].extend(f"{relative}: {line.strip()}"
                                        for line in duplicated_lines(before, theirs.read_text(), current.read_text()))
    return report


def removed_directory(project, base_files, relative):
    """The directory a new file lands in that the project deleted, or None.

    That is the nearest directory above `relative` that holds files in the base render: when none of
    them is left in the project (the sample module it replaced, say), the project removed it, and a
    file the template adds there belongs to what it removed. The project's root never counts."""
    for folder in pathlib.PurePosixPath(relative).parents:
        if folder == pathlib.PurePosixPath("."):
            return None
        inside = [path for path in base_files if pathlib.PurePosixPath(path).is_relative_to(folder)]
        if inside:
            return None if any((project / path).is_file() for path in inside) else folder.as_posix()
    return None


def duplicated_lines(project, template, merged):
    """Lines the merge holds more often than both the project and the template did.

    git merge-file inserts what the template added beside what the project added by hand without a
    conflict marker when the base has neither (a load, a recipe, a table row copied from another
    render), so both copies land. Lines with no letter or digit (a brace, a blank) repeat by nature
    and are left out."""
    project_counts, template_counts = collections.Counter(project.splitlines()), collections.Counter(template.splitlines())
    merged_counts = collections.Counter(merged.splitlines())
    return [line for line in merged_counts
            if re.search(r"[A-Za-z0-9]", line)
            and merged_counts[line] > max(project_counts[line], template_counts[line])]


def update(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the update's diff stands alone")
    # Renders read commits, so only tracked changes can make them differ from the checkout; an
    # untracked file there (the board's .kanban/, say) changes nothing.
    if git("status", "--porcelain", "--untracked-files=no"):
        print("Note: the template has uncommitted changes, which the update leaves out.", file=sys.stderr)
    note = unstamped_note(project, stamp)
    if note:
        print(note, file=sys.stderr)
    note = performance_note(project, stamp)
    if note:
        print(note, file=sys.stderr)
    old_commit, new_commit = resolve(stamp["commit"]), resolve(arguments.to)
    if old_commit == new_commit:
        print(f"{project.name} is already at {new_commit[:12]}.")
        return 0
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="template-update-") as directory:
        scratch = pathlib.Path(directory)
        base = render(old_commit, stamp, scratch)
        new = render(new_commit, stamp, scratch)
        swift_note = follow_project_swift(project, base, new)
        report = merge(project, base, new, f"template {old_commit[:12]}", f"template {new_commit[:12]}")
    regenerate = regenerate_modules(project)
    stamp.update(commit=new_commit)
    if performance_note(project, stamp):
        stamp["performance"] = False
    stamp.pop("modified", None)
    write_stamp(project, stamp)

    print(f"{project.name}: template {old_commit[:12]} → {new_commit[:12]}")
    for line in git("log", "--format=  %h %s", f"{old_commit}..{new_commit}").splitlines():
        print(line)
    print()
    return print_report(report, regenerate, swift_note)


def regenerate_modules(project):
    if not (project / "scripts" / "modules.py").is_file():
        return None
    return subprocess.run([sys.executable, "scripts/modules.py"], cwd=project, capture_output=True, text=True)


def print_report(report, regenerate, swift_note=None):
    labels = {
        "updated": "Updated (unchanged here, so taken whole)",
        "added": "Added",
        "removed": "Removed",
        "merged": "Merged cleanly",
        "conflicted": "CONFLICTS: resolve the <<<<<<< markers",
        "duplicated": "DUPLICATES: merged in twice with no markers (the project had added it by hand); keep one copy",
        "kept": "Kept",
        "skipped": "Skipped",
        "regenerated": "Generated by scripts/modules.py (regenerated, not merged)",
    }
    modules_conflicted = "scripts/modules.py" in report["conflicted"]
    if regenerate is not None and regenerate.returncode != 0 and "more than once" in regenerate.stderr:
        # git merge-file inserts a table the template added beside the project's own copy without a
        # conflict marker; scripts/modules.py refuses the duplicate, so report it with the conflicts.
        report["conflicted"].append("scripts/modules.py (a table or function is defined twice, with no markers; "
                                    "keep one, holding this project's rows)")
    for outcome, label in labels.items():
        if report[outcome]:
            print(f"{label}:")
            for entry in report[outcome]:
                print(f"  {entry}")
    if regenerate is not None and regenerate.returncode != 0 and modules_conflicted:
        # Its conflict markers aren't Python, so it fails before writing anything; the traceback
        # would only point at the first marker.
        print("\nscripts/modules.py still holds conflict markers, so the generated files weren't regenerated "
              "and are stale: resolve its markers, then run `just modules`.")
    elif regenerate is not None and regenerate.returncode != 0:
        print(f"\nscripts/modules.py failed, so the generated files are stale; fix it and run `just modules`:\n"
              f"{regenerate.stderr.strip()}")
    if swift_note:
        print(f"\n{swift_note}")
    print("\nNext: resolve any conflicts, `just modules`, `just test`, review `git diff`, then commit.")
    return 1 if report["conflicted"] or report["duplicated"] or (regenerate is not None and regenerate.returncode != 0) else 0


# Options that apply to some types only: the types each applies to.
TYPE_ONLY = {"wasm": ("library", "embedded"), "explore": ("library",), "views": ("library",), "examples": ("library",), "ios": ("library", "server"), "simulator": ("library", "server"),
             # Firmware, MCP servers and apps throw rather than trap.
             "performance": ("library", "server"), "fly": ("server",), "database": ("server",),
             # The workflows run in Linux containers; an iOS app's tests need a Mac.
             "ci": ("library", "server", "embedded", "mcp"), "trunk": ("library", "server", "embedded", "mcp")}


def add(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    wanted = [feature for feature in FEATURES if getattr(arguments, feature)]
    if not wanted:
        sys.exit("Name an option to add, such as --wasm")
    wrong_type = [feature for feature in wanted
                  if feature in TYPE_ONLY and stamp["type"] not in TYPE_ONLY[feature]]
    if wrong_type:
        sys.exit(f"{', '.join('--' + feature for feature in wrong_type)} doesn't apply to the {stamp['type']} type")
    if "trunk" in wanted and not (enabled(stamp, "ci") or "ci" in wanted):
        sys.exit("--trunk needs CI: the merge queue waits for CI's checks; add --ci with it")
    new_features = [feature for feature in wanted if not has(stamp, feature)]
    if not new_features:
        print(f"{project.name} already has {', '.join('--' + feature for feature in wanted)}.")
        return 0
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the diff shows only the new options")
    commit = resolve(stamp["commit"])
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    added = "".join(f"+{feature}" for feature in new_features)
    with tempfile.TemporaryDirectory(prefix="template-add-") as directory:
        scratch = pathlib.Path(directory)
        script = bootstrap_source(commit, scratch)
        unknown = [feature for feature in new_features if f"--{feature})" not in script]
        if unknown:
            sys.exit(f"The template at {commit[:12]}, which {project.name} is stamped with, has no "
                     f"{', '.join('--' + feature for feature in unknown)}; run ./template.py update first")
        with_options = dict(stamp, **{feature: True for feature in new_features})
        base = render(commit, stamp, scratch)
        new = render(commit, with_options, scratch, variant=added)
        swift_note = follow_project_swift(project, base, new)
        report = merge(project, base, new, f"template {commit[:12]}", f"template {commit[:12]} {added}")
    regenerate = regenerate_modules(project)
    write_stamp(project, with_options)

    print(f"{project.name}: {', '.join('--' + feature for feature in new_features)} at template {commit[:12]}\n")
    return print_report(report, regenerate, swift_note)


def remove(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    wanted = [feature for feature in FEATURES if getattr(arguments, feature)]
    if not wanted:
        sys.exit("Name an option to remove, such as --wasm")
    absent = [feature for feature in wanted if not has(stamp, feature)]
    if absent:
        sys.exit(f"{project.name} doesn't have {', '.join('--' + feature for feature in absent)} "
                 f"(its {STAMP} has it off), so there is nothing to remove")
    if "ci" in wanted and enabled(stamp, "trunk") and "trunk" not in wanted:
        sys.exit("--trunk needs CI: the merge queue waits for CI's checks; remove --trunk with it")
    kept_by = [feature for feature in wanted
               if feature in IMPLIED_BY and enabled(stamp, IMPLIED_BY[feature]) and IMPLIED_BY[feature] not in wanted]
    if kept_by:
        sys.exit(f"--{IMPLIED_BY[kept_by[0]]} brings --{kept_by[0]}'s files too, so removing --{kept_by[0]} alone "
                 f"changes nothing; remove --{IMPLIED_BY[kept_by[0]]} as well")
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the diff shows only the removed options")
    commit = resolve(stamp["commit"])
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    removed = "".join(f"-{feature}" for feature in wanted)
    with tempfile.TemporaryDirectory(prefix="template-remove-") as directory:
        scratch = pathlib.Path(directory)
        script = bootstrap_source(commit, scratch)
        # An option on by default is turned off by its --no- flag, which an older bootstrap.sh lacks.
        unknown = [feature for feature in wanted if feature in ON_BY_DEFAULT and f"--no-{feature})" not in script]
        if unknown:
            sys.exit(f"The template at {commit[:12]}, which {project.name} is stamped with, has no "
                     f"{', '.join('--no-' + feature for feature in unknown)}; run ./template.py update first")
        without_options = dict(stamp, **{feature: False for feature in wanted})
        base = render(commit, stamp, scratch)
        new = render(commit, without_options, scratch, variant=removed)
        swift_note = follow_project_swift(project, base, new)
        report = merge(project, base, new, f"template {commit[:12]}", f"template {commit[:12]} {removed}")
    regenerate = regenerate_modules(project)
    write_stamp(project, without_options)

    print(f"{project.name}: without {', '.join('--' + feature for feature in wanted)} at template {commit[:12]}\n")
    return print_report(report, regenerate, swift_note)


def retype(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    if stamp["type"] == arguments.type:
        print(f"{project.name} is already the {arguments.type} type.")
        return 0
    wrong_type = [feature for feature in TYPE_ONLY
                  if enabled(stamp, feature) and arguments.type not in TYPE_ONLY[feature]]
    if wrong_type:
        sys.exit(f"The {arguments.type} type doesn't take {', '.join('--' + feature for feature in wrong_type)}, "
                 f"which {project.name} has; take it out by hand first")
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the diff shows only the new type")
    commit = resolve(stamp["commit"])
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="template-retype-") as directory:
        scratch = pathlib.Path(directory)
        if f"--{arguments.type})" not in bootstrap_source(commit, scratch):
            sys.exit(f"The template at {commit[:12]}, which {project.name} is stamped with, has no "
                     f"{arguments.type} type; run ./template.py update first")
        retyped = dict(stamp, type=arguments.type)
        base = render(commit, stamp, scratch)
        new = render(commit, retyped, scratch, variant=f"-{arguments.type}")
        swift_note = follow_project_swift(project, base, new)
        report = merge(project, base, new, f"template {commit[:12]} {stamp['type']}",
                       f"template {commit[:12]} {arguments.type}")
    regenerate = regenerate_modules(project)
    write_stamp(project, retyped)

    print(f"{project.name}: {stamp['type']} -> {arguments.type} at template {commit[:12]}\n")
    return print_report(report, regenerate, swift_note)


def stamp_command(arguments):
    project = pathlib.Path(arguments.project).resolve()
    if not project.is_dir():
        sys.exit(f"No such directory: {project}")
    wrong_type = [feature for feature in TYPE_ONLY if getattr(arguments, feature) and arguments.type not in TYPE_ONLY[feature]]
    if wrong_type:
        sys.exit(f"{', '.join('--' + feature for feature in wrong_type)} doesn't apply to the {arguments.type} type")
    if arguments.trunk and not arguments.ci:
        sys.exit("--trunk needs CI: the merge queue waits for CI's checks")
    name = arguments.name or project.name
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
        sys.exit(f"The name must be the UpperCamelCase name the project was made with (a Swift module name), "
                 f"not {name!r}; pass it with --name")
    stamp = {
        "commit": resolve(arguments.commit),
        "name": name,
        "type": arguments.type,
        "benchmarks": arguments.benchmarks,
        "mutation": arguments.mutation,
        "fuzz": arguments.fuzz,
        "differential": arguments.differential,
        "wasm": arguments.wasm,
        "explore": arguments.explore,
        "views": arguments.views,
        "examples": arguments.examples,
        "ios": arguments.ios,
        "simulator": arguments.simulator,
        "performance": arguments.performance,
        "fly": arguments.fly,
        "database": arguments.database,
        "ci": arguments.ci,
        "trunk": arguments.trunk,
    }
    write_stamp(project, stamp)
    print(f"Stamped {project / STAMP} at {stamp['commit'][:12]}.")
    return 0


def status(arguments):
    roots = [pathlib.Path(root).expanduser().resolve() for root in arguments.root] or [TEMPLATE.parent]
    head = resolve("HEAD")
    rows = []
    for root in roots:
        for project in sorted(path for path in root.iterdir() if path.is_dir() and path != TEMPLATE):
            if (project / STAMP).is_file():
                stamp = json.loads((project / STAMP).read_text())
                behind = git("rev-list", "--count", f"{stamp['commit']}..{head}", check=False) or "?"
                state = "current" if behind == "0" else f"{behind} behind"
                found = unstamped_options(project, stamp) if {"name", "type"} <= stamp.keys() else []
                if found:
                    state += f"; has {' '.join('--' + feature for feature in found)}'s files, stamped without"
                rows.append((project.name, stamp["commit"][:12], state))
            elif (project / "scripts" / "modules.py").is_file() and (project / "AGENTS.md").is_file():
                rows.append((project.name, "-", "not stamped"))
    if not rows:
        print("No projects from this template found.")
        return 0
    width = max(len(name) for name, _, _ in rows)
    for name, commit, state in rows:
        print(f"{name:<{width}}  {commit:<12}  {state}")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    status_parser = commands.add_parser("status", help="every project and how far behind the template it is")
    status_parser.add_argument("--root", action="append", default=[], help="a directory of projects (default ~/workspace)")
    status_parser.set_defaults(run=status)

    update_parser = commands.add_parser("update", help="merge the template's changes into a project")
    update_parser.add_argument("project")
    update_parser.add_argument("--to", default="HEAD", help="the template revision to update to (default HEAD)")
    update_parser.set_defaults(run=update)

    stamp_parser = commands.add_parser("stamp", help="record which template commit and options a project matches")
    stamp_parser.add_argument("project")
    stamp_parser.add_argument("--type", choices=["library", "server", "embedded", "mcp", "app"], default="library")
    for feature in FEATURES:
        if feature in ON_BY_DEFAULT:
            stamp_parser.add_argument(f"--no-{feature}", dest=feature, action="store_false")
        else:
            stamp_parser.add_argument(f"--{feature}", action="store_true")
    stamp_parser.add_argument("--name", help="the project's name (default the directory's)")
    stamp_parser.add_argument("--commit", default="HEAD", help="the template revision it matches (default HEAD)")
    stamp_parser.set_defaults(run=stamp_command)

    add_parser = commands.add_parser("add", help="turn options on in a project made without them")
    add_parser.add_argument("project")
    for feature in FEATURES:
        add_parser.add_argument(f"--{feature}", action="store_true")
    add_parser.set_defaults(run=add)

    remove_parser = commands.add_parser("remove", help="turn options off in a project made with them")
    remove_parser.add_argument("project")
    for feature in FEATURES:
        remove_parser.add_argument(f"--{feature}", action="store_true")
    remove_parser.set_defaults(run=remove)

    retype_parser = commands.add_parser("retype", help="change a project's type")
    retype_parser.add_argument("project")
    retype_parser.add_argument("--type", choices=["library", "server", "embedded", "mcp", "app"], required=True)
    retype_parser.set_defaults(run=retype)

    arguments = parser.parse_args()
    return arguments.run(arguments)


if __name__ == "__main__":
    sys.exit(main())
