#!/usr/bin/env python3
"""Keep projects made from this template current.

  ./template.py status [--root DIR]...
      Every project under ~/workspace (or each --root): the template commit it is stamped with and
      how many template commits it is behind, or that it has no stamp yet.

  ./template.py update PROJECT [--to REVISION]
      Merge the template's changes since the project's stamp into PROJECT. The template is rendered
      at the stamped commit and at REVISION (default HEAD) with the project's name and options, and
      every file that changed between the two is merged three ways into the project with
      `git merge-file`. Conflicts are left marked in the files; the files scripts/modules.py
      generates are regenerated instead of merged. Nothing is committed. PROJECT must be a git
      checkout with no uncommitted changes, so `git diff` shows exactly what the update did.

  ./template.py stamp PROJECT [--type library|server|embedded|mcp] [--benchmarks] [--mutation] [--fuzz]
                              [--differential] [--wasm] [--explore] [--fly] [--database] [--no-ci]
                              [--name NAME] [--commit REVISION]
      Record that PROJECT matches the template at REVISION (default HEAD) with these options, for a
      project made before bootstrap.sh wrote stamps. Later updates merge only what changed after it.

  ./template.py add PROJECT [--benchmarks] [--mutation] [--fuzz] [--differential] [--wasm] [--explore]
                            [--fly] [--database] [--ci]
      Turn options on in a project made without them. The template is rendered at the stamped commit
      with the stamp's options and again with the new ones added, and every file that differs is
      merged three ways into the project, as `update` does; the stamp then records the options. It
      refuses an option the stamped commit's bootstrap.sh doesn't know (run `update` first) or one
      that doesn't apply to the project's type. Nothing is committed; PROJECT must have no
      uncommitted changes.

The stamp is PROJECT/.template.json, written by bootstrap.sh. .github/README.md, "Keeping
projects current", describes the workflow.
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

TEMPLATE = pathlib.Path(__file__).resolve().parent
STAMP = ".template.json"
GENERATED = "GENERATED by scripts/modules.py"


def git(*args, cwd=TEMPLATE, check=True):
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed in {cwd}:\n{result.stderr.strip()}")
    return result.stdout.strip()


def resolve(revision):
    return git("rev-parse", "--verify", f"{revision}^{{commit}}")


def read_stamp(project):
    path = project / STAMP
    if not path.is_file():
        sys.exit(f"{project} has no {STAMP}; adopt it first with ./template.py stamp (.github/README.md, \"Keeping projects current\")")
    return json.loads(path.read_text())


def write_stamp(project, stamp):
    (project / STAMP).write_text(json.dumps(stamp, indent=2) + "\n")


FEATURES = ("benchmarks", "mutation", "fuzz", "differential", "wasm", "explore", "fly", "database", "ci")
# Options on unless the stamp says otherwise: a stamp from before the option had it.
ON_BY_DEFAULT = ("ci",)


def enabled(stamp, feature):
    return stamp.get(feature, feature in ON_BY_DEFAULT)


def options(stamp):
    """bootstrap.sh's flags for the stamp. Only the features that differ from bootstrap's defaults
    are passed, so a template commit older than an option, which doesn't know its flag, renders
    every stamp that keeps the default."""
    flags = ["--type", stamp["type"]]
    for feature in FEATURES:
        if enabled(stamp, feature) and feature not in ON_BY_DEFAULT:
            flags.append(f"--{feature}")
        elif not enabled(stamp, feature) and feature in ON_BY_DEFAULT:
            flags.append(f"--no-{feature}")
    return flags


def bootstrap_source(commit, scratch):
    """bootstrap.sh at `commit`, from an archive of the template extracted once into `scratch`."""
    source = scratch / f"template-{commit[:12]}"
    if not source.is_dir():
        source.mkdir()
        archive = subprocess.run(["git", "archive", commit], cwd=TEMPLATE, capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", str(source)], input=archive, check=True)
    return (source / "bootstrap.sh").read_text()


def render(commit, stamp, scratch, variant=""):
    """The template at `commit`, rendered with the stamp's name and options; returns its directory."""
    if "--render-only" not in bootstrap_source(commit, scratch):
        sys.exit(f"The template at {commit[:12]} predates --render-only; stamp the project at a later commit")
    bootstrap = scratch / f"template-{commit[:12]}" / "bootstrap.sh"
    rendered = scratch / f"rendered-{commit[:12]}{variant}"
    result = subprocess.run(["bash", str(bootstrap), "--render-only", *options(stamp), stamp["name"], str(rendered)],
                            capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"Rendering the template at {commit[:12]} failed:\n{result.stderr.strip()}")
    return rendered


def files(root):
    return {path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file() and not path.is_symlink()}


def is_generated(path):
    try:
        with open(path, encoding="utf-8") as file:
            return any(GENERATED in file.readline() for _ in range(3))
    except (UnicodeDecodeError, OSError):
        return False


def is_text(path):
    try:
        path.read_text(encoding="utf-8")
        return True
    except UnicodeDecodeError:
        return False


def install(source, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def merge(project, base, new, base_label, new_label):
    """Merges every file that changed from `base` to `new` into `project`; returns a report by outcome."""
    report = {name: [] for name in ("updated", "added", "removed", "merged", "conflicted",
                                    "kept", "skipped", "regenerated")}
    empty = base.parent / "empty"
    empty.write_text("")
    for relative in sorted(files(base) | files(new)):
        if relative == STAMP:
            continue
        old, current, theirs = base / relative, project / relative, new / relative
        if old.is_file() and theirs.is_file() and old.read_bytes() == theirs.read_bytes():
            continue
        if is_generated(theirs if theirs.is_file() else old):
            report["regenerated"].append(relative)
            continue
        if not theirs.is_file():
            if not current.is_file():
                continue
            if current.read_bytes() == old.read_bytes():
                current.unlink()
                report["removed"].append(relative)
            else:
                report["kept"].append(f"{relative} (the template removed it; this project changed it)")
            continue
        if not current.is_file():
            if old.is_file():
                report["skipped"].append(f"{relative} (the template changed it; this project removed it)")
            else:
                install(theirs, current)
                report["added"].append(relative)
            continue
        if current.read_bytes() == theirs.read_bytes():
            continue
        if old.is_file() and current.read_bytes() == old.read_bytes():
            install(theirs, current)
            report["updated"].append(relative)
            continue
        if not (is_text(current) and is_text(theirs) and (not old.is_file() or is_text(old))):
            report["conflicted"].append(f"{relative} (binary; the template's version is at {theirs})")
            continue
        result = subprocess.run(
            ["git", "merge-file", "-L", "project", "-L", base_label, "-L", new_label, str(current), str(old if old.is_file() else empty), str(theirs)],
            capture_output=True, text=True)
        if result.returncode < 0 or result.returncode > 127:
            sys.exit(f"git merge-file failed on {relative}:\n{result.stderr.strip()}")
        report["conflicted" if result.returncode > 0 else "merged"].append(relative)
    return report


def update(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the update's diff stands alone")
    if git("status", "--porcelain"):
        print("Note: the template has uncommitted changes, which the update leaves out.", file=sys.stderr)
    old_commit, new_commit = resolve(stamp["commit"]), resolve(arguments.to)
    if old_commit == new_commit:
        print(f"{project.name} is already at {new_commit[:12]}.")
        return 0
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    with tempfile.TemporaryDirectory(prefix="template-update-") as directory:
        scratch = pathlib.Path(directory)
        base = render(old_commit, stamp, scratch)
        new = render(new_commit, stamp, scratch)
        report = merge(project, base, new, f"template {old_commit[:12]}", f"template {new_commit[:12]}")
    regenerate = regenerate_modules(project)
    stamp.update(commit=new_commit)
    stamp.pop("modified", None)
    write_stamp(project, stamp)

    print(f"{project.name}: template {old_commit[:12]} → {new_commit[:12]}")
    for line in git("log", "--format=  %h %s", f"{old_commit}..{new_commit}").splitlines():
        print(line)
    print()
    return print_report(report, regenerate)


def regenerate_modules(project):
    if not (project / "scripts" / "modules.py").is_file():
        return None
    return subprocess.run([sys.executable, "scripts/modules.py"], cwd=project, capture_output=True, text=True)


def print_report(report, regenerate):
    labels = {
        "updated": "Updated (unchanged here, so taken whole)",
        "added": "Added",
        "removed": "Removed",
        "merged": "Merged cleanly",
        "conflicted": "CONFLICTS: resolve the <<<<<<< markers",
        "kept": "Kept",
        "skipped": "Skipped",
        "regenerated": "Generated by scripts/modules.py (regenerated, not merged)",
    }
    for outcome, label in labels.items():
        if report[outcome]:
            print(f"{label}:")
            for entry in report[outcome]:
                print(f"  {entry}")
    if regenerate is not None and regenerate.returncode != 0:
        print(f"\nscripts/modules.py failed, so the generated files are stale; fix it and run `just modules`:\n"
              f"{regenerate.stderr.strip()}")
    print("\nNext: resolve any conflicts, `just modules`, `just test`, review `git diff`, then commit.")
    return 1 if report["conflicted"] or (regenerate is not None and regenerate.returncode != 0) else 0


# Options that apply to some types only: the types each applies to.
TYPE_ONLY = {"wasm": ("library", "embedded"), "explore": ("library",), "fly": ("server",), "database": ("server",)}


def add(arguments):
    project = pathlib.Path(arguments.project).resolve()
    stamp = read_stamp(project)
    wanted = [feature for feature in FEATURES if getattr(arguments, feature)]
    if not wanted:
        sys.exit("Name an option to add, such as --wasm")
    wrong_type = [feature for feature in wanted
                  if feature in TYPE_ONLY and stamp["type"] not in TYPE_ONLY[feature]]
    if wrong_type:
        sys.exit(f"{', '.join('--' + feature for feature in wrong_type)} doesn't apply to the {stamp['type']} type")
    new_features = [feature for feature in wanted if not enabled(stamp, feature)]
    if not new_features:
        print(f"{project.name} already has {', '.join('--' + feature for feature in wanted)}.")
        return 0
    if git("status", "--porcelain", cwd=project):
        sys.exit(f"{project} has uncommitted changes; commit or stash them so the diff shows only the new options")
    commit = resolve(stamp["commit"])
    if stamp.get("modified"):
        print("Note: the project was made from a template with uncommitted changes, so its stamp is approximate.",
              file=sys.stderr)
    added = "".join(f"+{feature}" for feature in new_features)
    with tempfile.TemporaryDirectory(prefix="template-add-") as directory:
        scratch = pathlib.Path(directory)
        script = bootstrap_source(commit, scratch)
        unknown = [feature for feature in new_features if f"--{feature})" not in script]
        if unknown:
            sys.exit(f"The template at {commit[:12]}, which {project.name} is stamped with, has no "
                     f"{', '.join('--' + feature for feature in unknown)}; run ./template.py update first")
        with_options = dict(stamp, **{feature: True for feature in new_features})
        base = render(commit, stamp, scratch)
        new = render(commit, with_options, scratch, variant=added)
        report = merge(project, base, new, f"template {commit[:12]}", f"template {commit[:12]} {added}")
    regenerate = regenerate_modules(project)
    write_stamp(project, with_options)

    print(f"{project.name}: {', '.join('--' + feature for feature in new_features)} at template {commit[:12]}\n")
    return print_report(report, regenerate)


def stamp_command(arguments):
    project = pathlib.Path(arguments.project).resolve()
    if not project.is_dir():
        sys.exit(f"No such directory: {project}")
    wrong_type = [feature for feature in TYPE_ONLY if getattr(arguments, feature) and arguments.type not in TYPE_ONLY[feature]]
    if wrong_type:
        sys.exit(f"{', '.join('--' + feature for feature in wrong_type)} doesn't apply to the {arguments.type} type")
    name = arguments.name or project.name
    if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
        sys.exit(f"The name must be the UpperCamelCase name the project was made with (a Swift module name), "
                 f"not {name!r}; pass it with --name")
    stamp = {
        "commit": resolve(arguments.commit),
        "name": name,
        "type": arguments.type,
        "benchmarks": arguments.benchmarks,
        "mutation": arguments.mutation,
        "fuzz": arguments.fuzz,
        "differential": arguments.differential,
        "wasm": arguments.wasm,
        "explore": arguments.explore,
        "fly": arguments.fly,
        "database": arguments.database,
        "ci": arguments.ci,
    }
    write_stamp(project, stamp)
    print(f"Stamped {project / STAMP} at {stamp['commit'][:12]}.")
    return 0


def status(arguments):
    roots = [pathlib.Path(root).expanduser().resolve() for root in arguments.root] or [TEMPLATE.parent]
    head = resolve("HEAD")
    rows = []
    for root in roots:
        for project in sorted(path for path in root.iterdir() if path.is_dir() and path != TEMPLATE):
            if (project / STAMP).is_file():
                stamp = json.loads((project / STAMP).read_text())
                behind = git("rev-list", "--count", f"{stamp['commit']}..{head}", check=False) or "?"
                state = "current" if behind == "0" else f"{behind} behind"
                rows.append((project.name, stamp["commit"][:12], state))
            elif (project / "scripts" / "modules.py").is_file() and (project / "AGENTS.md").is_file():
                rows.append((project.name, "-", "not stamped"))
    if not rows:
        print("No projects from this template found.")
        return 0
    width = max(len(name) for name, _, _ in rows)
    for name, commit, state in rows:
        print(f"{name:<{width}}  {commit:<12}  {state}")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)

    status_parser = commands.add_parser("status", help="every project and how far behind the template it is")
    status_parser.add_argument("--root", action="append", default=[], help="a directory of projects (default ~/workspace)")
    status_parser.set_defaults(run=status)

    update_parser = commands.add_parser("update", help="merge the template's changes into a project")
    update_parser.add_argument("project")
    update_parser.add_argument("--to", default="HEAD", help="the template revision to update to (default HEAD)")
    update_parser.set_defaults(run=update)

    stamp_parser = commands.add_parser("stamp", help="record which template commit and options a project matches")
    stamp_parser.add_argument("project")
    stamp_parser.add_argument("--type", choices=["library", "server", "embedded", "mcp"], default="library")
    for feature in FEATURES:
        if feature in ON_BY_DEFAULT:
            stamp_parser.add_argument(f"--no-{feature}", dest=feature, action="store_false")
        else:
            stamp_parser.add_argument(f"--{feature}", action="store_true")
    stamp_parser.add_argument("--name", help="the project's name (default the directory's)")
    stamp_parser.add_argument("--commit", default="HEAD", help="the template revision it matches (default HEAD)")
    stamp_parser.set_defaults(run=stamp_command)

    add_parser = commands.add_parser("add", help="turn options on in a project made without them")
    add_parser.add_argument("project")
    for feature in FEATURES:
        add_parser.add_argument(f"--{feature}", action="store_true")
    add_parser.set_defaults(run=add)

    arguments = parser.parse_args()
    return arguments.run(arguments)


if __name__ == "__main__":
    sys.exit(main())
